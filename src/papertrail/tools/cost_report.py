"""Cost report from the budget ledger (runs/_spend.jsonl): per run, per model and per role, as markdown.

    python -m papertrail.tools.cost_report [--ledger runs/_spend.jsonl] [--out results/COSTS.md]

The ledger is the code-enforced record of every paid call (OpenRouter's returned cost, USD). Nothing in the report is typed by hand.
Run ids are described in RUN_LABELS; an id that is not listed is reported without a description.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

from papertrail.paths import ROOT

RUN_LABELS = {
    "20261012-112632": "First attempt on the test paper (2505.06120), cheapest `--dev` models; the run directory was deleted afterwards",
    "20261012-181956": "Test paper, final models (Claude author, Gemini judge) after the quality pass; kept in `results/test-paper-2505.06120/`",
    "20261015-155838": "Final paper (2510.22954), final models; kept in `results/final-paper-2510.22954/`",
    "e2e-fake": "Offline end-to-end tests with scripted fake models",
}


def load(ledger: Path) -> list[dict]:
    return [json.loads(line) for line in ledger.read_text(encoding="utf-8").splitlines() if line.strip()]


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def report(entries: list[dict], caps: dict | None = None) -> str:
    total = sum(e["usd"] for e in entries)
    by_run, calls = defaultdict(float), defaultdict(int)
    by_model, by_run_role, by_run_model = defaultdict(float), defaultdict(lambda: defaultdict(float)), defaultdict(lambda: defaultdict(float))
    for e in entries:
        by_run[e["run"]] += e["usd"]
        calls[e["run"]] += 1
        by_model[e["model"]] += e["usd"]
        by_run_role[e["run"]][e["role"]] += e["usd"]
        by_run_model[e["run"]][e["model"]] += e["usd"]

    lines = ["# Costs", "", "Generated by `python -m papertrail.tools.cost_report` from the budget ledger (`results/cost_ledger.jsonl`, a copy of `runs/_spend.jsonl`). "
             "The ledger records every paid model call (OpenRouter's returned cost, USD). Local models (Ollama) and the Kaggle GPUs of the extra study cost nothing.", ""]
    lines += [f"**Total spent: ${total:.2f}** over {len(entries)} calls." + (f" Caps in `config/budget.yaml`: ${caps['per_run_usd']:.2f} per run, ${caps['total_usd']:.2f} in total." if caps else ""), ""]
    lines += ["## By run", "", table(["Run", "What it was", "Calls", "USD"],
                                     [[f"`{r}`", RUN_LABELS.get(r, ""), str(calls[r]), f"{v:.2f}"] for r, v in sorted(by_run.items())] + [["**Total**", "", str(len(entries)), f"**{total:.2f}**"]]), ""]
    lines += ["## By model (all runs)", "", table(["Model", "USD"], [[f"`{m}`", f"{v:.2f}"] for m, v in sorted(by_model.items(), key=lambda x: -x[1])]), ""]
    for r in sorted(by_run):
        if r == "e2e-fake":
            continue
        lines += [f"## Run `{r}`", "", RUN_LABELS.get(r, ""), "",
                  table(["Role", "USD"], [[role, f"{v:.3f}"] for role, v in sorted(by_run_role[r].items(), key=lambda x: -x[1])]), "",
                  table(["Model", "USD"], [[f"`{m}`", f"{v:.3f}"] for m, v in sorted(by_run_model[r].items(), key=lambda x: -x[1])]), ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ledger", default=str(ROOT / "runs" / "_spend.jsonl"))
    ap.add_argument("--out", default=str(ROOT / "results" / "COSTS.md"))
    a = ap.parse_args()
    caps = None
    try:
        import yaml

        caps = yaml.safe_load((ROOT / "config" / "budget.yaml").read_text(encoding="utf-8"))
    except Exception:  # the report does not need the caps
        pass
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report(load(Path(a.ledger)), caps) + "\n", encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
